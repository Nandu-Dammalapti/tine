"""The Postgres translation, and the ledger run on a real Postgres server when
TINE_TEST_POSTGRES_URL names an empty database to use (its tables are dropped)."""

import os

import pytest

from tine.db import Row, is_postgres, translate
from tine.ledger import Ledger
from tine.shadow import ShadowStore


def test_placeholders_and_sqlite_statements_are_translated():
    assert translate("SELECT * FROM requests WHERE tenant=? AND id=?", ("a", "b")) == [
        ("SELECT * FROM requests WHERE tenant=%s AND id=%s", ("a", "b"))]
    assert translate("INSERT INTO t (a, b) VALUES (:a, :b)", {"a": 1, "b": 2}) == [
        ("INSERT INTO t (a, b) VALUES (%(a)s, %(b)s)", {"a": 1, "b": 2})]
    assert translate("PRAGMA journal_mode=WAL") is None
    (info,) = translate("PRAGMA table_info(shadow_runs)")
    assert "information_schema.columns" in info[0] and info[1] == ("shadow_runs",)
    assert translate("BEGIN IMMEDIATE")[0][0].startswith("SELECT pg_advisory_xact_lock(")
    assert translate("INSERT OR IGNORE INTO ledger_state VALUES(1, 0)")[0][0] == (
        "INSERT INTO ledger_state VALUES(1, 0) ON CONFLICT DO NOTHING")
    assert "shadow_counts.count+1" in translate(
        "INSERT INTO shadow_counts VALUES (?,?,1) ON CONFLICT(tenant, name) DO UPDATE SET count=count+1")[0][0]
    assert translate("SELECT '5%' WHERE a=?", (1,))[0][0] == "SELECT '5%%' WHERE a=%s"
    assert translate("SELECT '5%'") == [("SELECT '5%'", None)]


def test_tables_get_wide_numbers_and_a_rowid_and_the_trigger_is_plpgsql():
    (table,) = translate("CREATE TABLE IF NOT EXISTS t (a INTEGER NOT NULL, b REAL, "
                         "c INTEGER CHECK(c IN (0, 1) OR c IS NULL))")
    assert "a BIGINT NOT NULL, b DOUBLE PRECISION" in table[0]
    assert table[0].rstrip().endswith("rowid BIGINT GENERATED ALWAYS AS IDENTITY)")
    (events,) = translate("CREATE TABLE IF NOT EXISTS e (event_id INTEGER PRIMARY KEY AUTOINCREMENT, x TEXT)")
    assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in events[0] and "rowid" not in events[0]
    function, trigger = translate("CREATE TRIGGER IF NOT EXISTS e_no_update BEFORE UPDATE ON e BEGIN SELECT "
                                  "RAISE(ABORT, 'e is append-only'); END")
    assert "plpgsql" in function[0] and "RAISE EXCEPTION 'e is append-only'" in function[0]
    assert trigger[0] == "CREATE OR REPLACE TRIGGER e_no_update BEFORE UPDATE ON e FOR EACH ROW EXECUTE FUNCTION e_append_only()"


def test_rows_read_by_name_or_position_and_urls_are_recognised():
    row = Row(["a", "b"], [1, 2])
    assert row["b"] == 2 and row[0] == 1 and dict(row) == {"a": 1, "b": 2}
    assert is_postgres("postgresql://x/y") and is_postgres("postgres://x") and not is_postgres("ledger.sqlite3")
    assert Ledger().backend == "sqlite"


def test_a_database_url_that_is_not_postgres_is_refused():
    from tine.proxy import ProxyConfig, create_app
    with pytest.raises(ValueError, match="TINE_DATABASE_URL"):
        create_app(ProxyConfig(tenant_keys={"t": "a"}, database_url="mysql://x"))


POSTGRES = os.environ.get("TINE_TEST_POSTGRES_URL")


@pytest.mark.skipif(not POSTGRES, reason="set TINE_TEST_POSTGRES_URL to an empty Postgres database to run")
def test_the_ledger_and_shadow_store_run_on_postgres():
    import psycopg
    with psycopg.connect(POSTGRES, autocommit=True) as connection:
        for table in ("requests", "outcome_events", "ledger_state", "shadow_runs", "shadow_counts", "drift_events"):
            connection.execute(f"DROP TABLE IF EXISTS {table} CASCADE")
    ledger = Ledger(POSTGRES)
    assert ledger.backend == "postgres"
    body = {"messages": [{"role": "user", "content": "q"}]}
    first = ledger.record(tenant="a", provider="openai", model="m", request_body=body, response_body={"x": 1},
                          upstream_status=200, cost_usd=0.5, routing_cost_usd=0.0, baseline_cost_usd=1.0,
                          input_tokens=2**40)
    assert ledger.get("a", first)["input_tokens"] == 2**40 and "rowid" not in ledger.get("a", first)
    assert ledger.update_outcome("a", first, True)
    assert ledger.cached("a", "openai", body)["request_id"] == first
    assert ledger.report("a")["verified_savings_usd"] == pytest.approx(0.5)
    assert ledger.fill_usage("a", first, output_tokens=7) and ledger.get("a", first)["output_tokens"] == 7
    assert [event["fields"] for event in ledger.outcome_events("a", first)] == [{"success": True}]
    with pytest.raises(psycopg.Error):
        ledger._db.execute("DELETE FROM outcome_events")
    store = ShadowStore(ledger)
    store.count("a", "streamed")
    store.count("a", "streamed")
    assert store.counts("a")["streamed"] == 2
    assert store.note_drift("a", {"drift_policy": "openai", "drift_check": "warning", "drift_policies": None})
    assert store.drift_history("a")[0]["status"] == "warning"
    assert ledger.billing("a")["lines"] == []
    ledger.close()
    again = Ledger(POSTGRES)  # opening an existing ledger changes nothing
    assert again.get("a", first)["success"] is True
    again.close()
