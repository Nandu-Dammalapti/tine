"""The ledger's database connection: SQLite by default, or Postgres from a URL.

``Ledger`` and ``ShadowStore`` write their SQL once, in SQLite's dialect. A Postgres
connection (``TINE_DATABASE_URL=postgresql://...``, needs the optional ``psycopg``
package) is wrapped so that the same statements run there:

- ``?`` and ``:name`` placeholders become ``%s`` and ``%(name)s``;
- ``PRAGMA table_info(t)`` reads ``information_schema``; other PRAGMAs do nothing;
- ``BEGIN IMMEDIATE`` takes a transaction-level advisory lock, so that writers that
  read before they write are serialised across processes, as SQLite's lock does;
- ``CREATE TABLE`` gets 64-bit integers, double-precision reals and an identity
  column named ``rowid``, which SQLite has built in;
- ``INSERT OR IGNORE`` becomes ``ON CONFLICT DO NOTHING``, and the append-only trigger
  on ``outcome_events`` becomes a PL/pgSQL trigger.

The wrapper has the part of ``sqlite3.Connection`` the ledger uses: ``execute``, a
context manager that commits or rolls back, and ``close``. Rows can be read by name or
by position. Statements outside a ``with`` block run in autocommit mode.
"""

from __future__ import annotations

import re
from typing import Any

POSTGRES_SCHEMES = ("postgresql://", "postgres://")
# The advisory lock ``BEGIN IMMEDIATE`` stands for.
WRITE_LOCK = 7_346_201


def is_postgres(target: Any) -> bool:
    return isinstance(target, str) and target.startswith(POSTGRES_SCHEMES)


class Row(dict):
    """A row read by column name, or by position as sqlite3.Row allows."""

    def __init__(self, names, values) -> None:
        super().__init__(zip(names, values))
        self._values = tuple(values)

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)


def _row_factory(cursor):
    names = [column.name for column in cursor.description or ()]
    return lambda values: Row(names, values)


class _Empty:
    """The cursor of a statement that does nothing on Postgres."""

    rowcount = 0

    def fetchone(self):
        return None

    def fetchall(self):
        return []

    def __iter__(self):
        return iter(())


_TABLE_INFO = re.compile(r"\s*PRAGMA\s+table_info\((\w+)\)\s*", re.IGNORECASE)
_TRIGGER = re.compile(r"\s*CREATE TRIGGER IF NOT EXISTS (\w+) BEFORE (UPDATE|DELETE) ON (\w+) BEGIN SELECT "
                      r"RAISE\(ABORT, '([^']*)'\); END\s*", re.IGNORECASE)
_NAMED = re.compile(r"(?<![:\w]):([A-Za-z_]\w*)")


def translate(sql: str, params: Any = ()) -> list[tuple[str, Any]] | None:
    """The Postgres statements for one ledger statement, or None when it does nothing."""
    found = _TABLE_INFO.fullmatch(sql)
    if found:
        return [("SELECT column_name AS name FROM information_schema.columns "
                 "WHERE table_schema = current_schema() AND table_name = %s ORDER BY ordinal_position",
                 (found.group(1).lower(),))]
    if re.match(r"\s*PRAGMA\b", sql, re.IGNORECASE):
        return None
    if re.fullmatch(r"\s*BEGIN IMMEDIATE\s*", sql, re.IGNORECASE):
        return [(f"SELECT pg_advisory_xact_lock({WRITE_LOCK})", ())]
    found = _TRIGGER.fullmatch(sql)
    if found:
        name, action, table, message = found.groups()
        function = f"{table}_append_only"
        return [(f"CREATE OR REPLACE FUNCTION {function}() RETURNS trigger LANGUAGE plpgsql AS "
                 f"$$ BEGIN RAISE EXCEPTION '{message}'; END $$", ()),
                (f"CREATE OR REPLACE TRIGGER {name} BEFORE {action} ON {table} FOR EACH ROW "
                 f"EXECUTE FUNCTION {function}()", ())]
    if re.match(r"\s*CREATE TABLE", sql, re.IGNORECASE):
        sql = re.sub(r"\bINTEGER PRIMARY KEY AUTOINCREMENT\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                     sql)
        sql = re.sub(r"\bINTEGER\b", "BIGINT", sql)
        sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql)
        if "AUTOINCREMENT" not in sql and "GENERATED" not in sql:
            closing = sql.rstrip().rfind(")")
            sql = sql[:closing] + ",\n    rowid BIGINT GENERATED ALWAYS AS IDENTITY" + sql[closing:]
        return [(sql, ())]
    if re.match(r"\s*ALTER TABLE \w+ ADD COLUMN", sql, re.IGNORECASE):
        sql = re.sub(r"\bINTEGER\b", "BIGINT", re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql))
    ignore = re.match(r"\s*INSERT OR IGNORE INTO", sql, re.IGNORECASE)
    if ignore:
        sql = "INSERT INTO" + sql[ignore.end():] + " ON CONFLICT DO NOTHING"
    # Postgres needs the target table named in an upsert's own column reference.
    sql = re.sub(r"DO UPDATE SET count=count\+1", "DO UPDATE SET count=shadow_counts.count+1", sql)
    if not params:
        # psycopg reads placeholders only when it is given parameters.
        return [(sql, None)]
    sql = sql.replace("%", "%%")
    if isinstance(params, dict):
        sql = _NAMED.sub(lambda match: f"%({match.group(1)})s", sql)
    else:
        sql = sql.replace("?", "%s")
    return [(sql, params)]


class PostgresConnection:
    """A Postgres connection with the part of sqlite3.Connection the ledger uses."""

    def __init__(self, url: str) -> None:
        try:
            import psycopg
        except ImportError:
            raise ValueError("TINE_DATABASE_URL names Postgres, but the psycopg package is not installed: "
                             "pip install 'psycopg[binary]'") from None
        self._psycopg = psycopg
        try:
            self._conn = psycopg.connect(url, autocommit=True, row_factory=_row_factory)
        except psycopg.Error as error:
            # The message can repeat the URL, which may hold a password.
            raise ValueError(f"Could not connect to the Postgres database: {type(error).__name__}") from None
        self._transactions: list = []

    def execute(self, sql: str, params: Any = ()):
        statements = translate(sql, params)
        if statements is None:
            return _Empty()
        cursor = None
        for text, values in statements:
            cursor = self._conn.execute(text, values or None)
        return cursor

    def __enter__(self):
        transaction = self._conn.transaction()
        transaction.__enter__()
        self._transactions.append(transaction)
        return self

    def __exit__(self, kind, value, traceback):
        return self._transactions.pop().__exit__(kind, value, traceback)

    def close(self) -> None:
        self._conn.close()
